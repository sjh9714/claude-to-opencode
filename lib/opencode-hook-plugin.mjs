const SUPPORTED_EVENTS = new Set(['PreToolUse', 'PostToolUse']);

const groupsOf = (settings, event) => {
  const groups = settings?.hooks?.[event];
  return Array.isArray(groups) ? groups : [];
};

export function inspectOpenCodeHookBridge(hookConfigs = []) {
  let supported = 0;
  let skipped = 0;
  const unsupportedEvents = new Set();

  for (const config of hookConfigs) {
    for (const [event, groups] of Object.entries(config.settings?.hooks ?? {})) {
      if (!Array.isArray(groups)) continue;
      for (const group of groups) {
        const handlers = Array.isArray(group?.hooks) ? group.hooks : [];
        for (const handler of handlers) {
          const usable = SUPPORTED_EVENTS.has(event)
            && !group?.if
            && handler?.type === 'command'
            && typeof handler.command === 'string'
            && handler.command.trim()
            && !handler.if
            && !handler.async;
          if (usable) supported += 1;
          else {
            skipped += 1;
            if (!SUPPORTED_EVENTS.has(event)) unsupportedEvents.add(event);
          }
        }
      }
    }
  }

  return {
    supported,
    skipped,
    unsupportedEvents: [...unsupportedEvents].sort(),
  };
}

export function renderOpenCodeHookPlugin() {
  return String.raw`// Generated by claude-to-opencode. Reads Claude settings at runtime.
import { spawn } from "node:child_process";
import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { homedir } from "node:os";
import path from "node:path";

const TOOL_NAMES = {
  bash: "Bash",
  edit: "Edit",
  glob: "Glob",
  grep: "Grep",
  read: "Read",
  skill: "Skill",
  task: "Agent",
  todowrite: "TodoWrite",
  webfetch: "WebFetch",
  websearch: "WebSearch",
  write: "Write",
};

const claudeRoot = () => process.env.CLAUDE_CONFIG_DIR
  || path.join(process.env.HOME || homedir(), ".claude");

function projectRoot(directory) {
  let current = path.resolve(directory);
  while (true) {
    if (existsSync(path.join(current, ".git"))) return current;
    const parent = path.dirname(current);
    if (parent === current) return path.resolve(directory);
    current = parent;
  }
}

const settingsFiles = (project) => [
  path.join(claudeRoot(), "settings.json"),
  path.join(project, ".claude", "settings.json"),
  path.join(project, ".claude", "settings.local.json"),
];

async function readSettings(project) {
  const values = [];
  for (const file of settingsFiles(project)) {
    try {
      values.push(JSON.parse(await readFile(file, "utf8")));
    } catch {
      // Missing or malformed source settings do not break OpenCode startup.
    }
  }
  if (values.some((value) => value?.disableAllHooks === true)) return [];
  return values;
}

function claudeToolName(tool) {
  const key = String(tool || "").toLowerCase();
  return TOOL_NAMES[key] || String(tool || "");
}

function matches(matcher, value) {
  if (matcher === undefined || matcher === null || matcher === "" || matcher === "*") return true;
  const pattern = String(matcher);
  if (/^[A-Za-z0-9_|]+$/.test(pattern)) return pattern.split("|").includes(value);
  try {
    return new RegExp(pattern).test(value);
  } catch {
    return false;
  }
}

async function handlersFor(event, tool, project) {
  const handlers = [];
  const seen = new Set();
  for (const settings of await readSettings(project)) {
    const groups = settings?.hooks?.[event];
    if (!Array.isArray(groups)) continue;
    for (const group of groups) {
      if (group?.if || !matches(group?.matcher, tool)) continue;
      for (const handler of Array.isArray(group?.hooks) ? group.hooks : []) {
        if (handler?.type !== "command" || typeof handler.command !== "string"
          || !handler.command.trim() || handler.if || handler.async) continue;
        const key = JSON.stringify([handler.command, handler.args || []]);
        if (seen.has(key)) continue;
        seen.add(key);
        handlers.push(handler);
      }
    }
  }
  return handlers;
}

function run(handler, payload, directory, project) {
  return new Promise((resolve) => {
    const args = Array.isArray(handler.args) ? handler.args.map(String) : [];
    let stdout = "";
    let stderr = "";
    let settled = false;
    const finish = (result) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve(result);
    };
    const child = spawn(handler.command, args, {
      cwd: directory,
      env: { ...process.env, CLAUDE_PROJECT_DIR: project },
      shell: args.length === 0,
      windowsHide: true,
      stdio: ["pipe", "pipe", "pipe"],
    });
    const timer = setTimeout(() => {
      child.kill();
      finish({ code: null, stdout, stderr, timedOut: true });
    }, Math.max(1, Number(handler.timeout) || 600) * 1000);
    child.stdout.on("data", (chunk) => {
      if (stdout.length < 100000) stdout += String(chunk);
    });
    child.stderr.on("data", (chunk) => {
      if (stderr.length < 100000) stderr += String(chunk);
    });
    child.on("error", (error) => finish({ code: 1, stdout, stderr: error.message }));
    child.on("close", (code) => finish({ code, stdout, stderr }));
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify(payload));
  });
}

function structured(stdout) {
  const text = String(stdout || "").trimStart();
  if (!text.startsWith("{")) return null;
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

function payload(event, input, args, directory, response) {
  return {
    session_id: input.sessionID,
    transcript_path: "",
    cwd: directory,
    permission_mode: "default",
    hook_event_name: event,
    tool_name: claudeToolName(input.tool),
    tool_input: args,
    ...(response === undefined ? {} : { tool_response: response }),
    tool_use_id: input.callID,
  };
}

export const ClaudeCodeHooks = async ({ directory }) => {
  const project = projectRoot(directory);
  return ({
  "tool.execute.before": async (input, output) => {
    const tool = claudeToolName(input.tool);
    const handlers = await handlersFor("PreToolUse", tool, project);
    const results = await Promise.all(handlers.map((handler) => run(
      handler,
      payload("PreToolUse", input, output.args, directory),
      directory,
      project,
    )));
    for (const result of results) {
      const data = structured(result.stdout);
      const specific = data?.hookSpecificOutput;
      const denied = result.code === 2
        || specific?.permissionDecision === "deny"
        || data?.decision === "block";
      if (denied) {
        throw new Error(specific?.permissionDecisionReason || data?.reason
          || result.stderr.trim() || "Blocked by a Claude Code PreToolUse hook");
      }
      if (specific?.updatedInput && typeof specific.updatedInput === "object") {
        for (const key of Object.keys(output.args)) delete output.args[key];
        Object.assign(output.args, specific.updatedInput);
      }
    }
  },
  "tool.execute.after": async (input, output) => {
    const tool = claudeToolName(input.tool);
    const handlers = await handlersFor("PostToolUse", tool, project);
    const results = await Promise.all(handlers.map((handler) => run(
      handler,
      payload("PostToolUse", input, input.args, directory, {
        title: output.title,
        output: output.output,
        metadata: output.metadata,
      }),
      directory,
      project,
    )));
    const feedback = [];
    for (const result of results) {
      const data = structured(result.stdout);
      if (data?.hookSpecificOutput?.updatedToolOutput !== undefined) {
        output.output = typeof data.hookSpecificOutput.updatedToolOutput === "string"
          ? data.hookSpecificOutput.updatedToolOutput
          : JSON.stringify(data.hookSpecificOutput.updatedToolOutput);
      }
      const context = data?.hookSpecificOutput?.additionalContext;
      if (typeof context === "string" && context) feedback.push(context);
      if (result.code === 2) feedback.push(result.stderr.trim() || "Claude Code PostToolUse hook failed");
      if (data?.decision === "block" && data.reason) feedback.push(String(data.reason));
    }
    if (feedback.length) output.output += "\n\nClaude Code hook feedback\n" + feedback.join("\n");
  },
  });
};
`;
}
